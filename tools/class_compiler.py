def encode(value: object) -> bytes:
    return (json.dumps(value, sort_keys=True, indent=2, ensure_ascii=False) + '\n').encode()


def read_json(sources: dict[str, bytes], name: str) -> dict:
    def pairs(items):
        value = {}
        for key, item in items:
            if key in value:
                raise ValueError(f'{name}: duplicate JSON field {key}')
            value[key] = item
        return value
    value = json.loads(sources[name], object_pairs_hook=pairs)
    if not isinstance(value, dict) or value.get('format') != 1:
        raise ValueError(f'{name}: expected data format 1')
    return value


def safe_path(value: str) -> str:
    if (not value or value.startswith('/') or len(value) > 240
            or any(part in {'', '.', '..'} for part in value.split('/'))
            or re.fullmatch(r'[A-Za-z0-9_./@+ -]+', value) is None):
        raise ValueError('noncanonical catalog path')
    return value


def assignment_data(text: str, values: dict[str, str], provenance: dict[str, str],
                    source: str, *, literals: bool = False, defaults_only: bool = False) -> None:
    """Restricted assignments, never shell evaluation or inherited environment.

    Public data permits parent references and ${NAME:-literal} defaults only.
    Single quotes are literal; double quotes support only shell's four literal
    escapes. Unquoted values use a bounded non-whitespace literal grammar.
    Duplicate assignments within a source and unresolved references fail.
    """
    seen = set()
    for number, line in enumerate(text.splitlines(), 1):
        if not line or line.startswith('#'):
            continue
        match = ASSIGNMENT.fullmatch(line)
        if match is None or len(line) > 65536:
            raise ValueError(f'{source}:{number}: invalid assignment grammar')
        name, raw = match.groups()
        if source.startswith('hosts/profiles/') and name.startswith(('DIR_', 'FILE_', 'INSTALLER_', 'TARGET_', 'REPOSITORY_')):
            raise ValueError(f'{source}:{number}: profile cannot override an invariant path, suite or repository owner')
        if name in seen:
            raise ValueError(f'{source}:{number}: duplicate assignment {name}')
        seen.add(name)
        expand = False
        if raw.startswith("'") and raw.endswith("'"):
            value = raw[1:-1]
            if "'" in value:
                raise ValueError(f'{source}:{number}: invalid literal quoting')
        elif raw.startswith('"') and raw.endswith('"'):
            value = raw[1:-1]
            if re.search(r'(?<!\\)"', value) or re.search(r'\\[^\\"$`]', value):
                raise ValueError(f'{source}:{number}: invalid quoted escape')
            # Shield explicitly escaped dollars during reference expansion.
            value = value.replace(r'\$', '\x01')
            value = re.sub(r'\\([\\"`])', r'\1', value)
            expand = not literals
        elif re.fullmatch(r'[A-Za-z0-9_./:@%+,-]*', raw):
            value = raw
        else:
            raise ValueError(f'{source}:{number}: unsupported assignment value')
        if expand:
            def reference(match: re.Match[str]) -> str:
                parent, operator, default = match.groups()
                if parent in values and (values[parent] or operator != ':-'):
                    return values[parent]
                if operator:
                    return default or ''
                raise ValueError(f'{source}:{number}: undefined parent {parent}')
            value = REFERENCE.sub(reference, value)
            if '$' in value or '`' in value:
                raise ValueError(f'{source}:{number}: unsupported expansion')
        elif not literals and ('$' in value or '`' in value) and not raw.startswith("'"):
            raise ValueError(f'{source}:{number}: executable expansion is forbidden')
        value = value.replace('\x01', '$')
        if source.startswith('hosts/profiles/') and '__INSTALLER_' in value:
            raise ValueError(f'{source}:{number}: profile data requires ordinary variable references, not template tokens')
        if any(ord(char) < 32 for char in value) or len(value) > 65536:
            raise ValueError(f'{source}:{number}: invalid data value')
        if not defaults_only or name not in values:
            values[name] = value
            provenance[name] = f'{source}:{number}'


def repository_data(text: str, suite: str, supported: set[str]) -> dict[str, str]:
    """Mirror the early awk data grammar at the owning build boundary.

    This deliberately has fewer forms than profile assignment_data: quoted
    literals and earlier ${PARENT} references only, with an exact vocabulary.
    It never evaluates shell, imports installer code, or reads inherited values.
    """
    if suite not in {'forky', 'trixie'}:
        raise ValueError('repo.env requires a supported suite')
    values = {'INSTALLER_SUITE': suite}
    seen = set()
    for number, line in enumerate(text.splitlines(), 1):
        if number > 512 or len(line) > 4096:
            raise ValueError('repo.env exceeds configuration limits')
        if not line or line.startswith('#'):
            continue
        match = re.fullmatch(r'([A-Z][A-Z0-9_]*)="([^"]*)"', line)
        if match is None:
            raise ValueError(f'repo.env:{number}: invalid data assignment')
        name, value = match.groups()
        if name not in supported or name in seen:
            raise ValueError(f'repo.env:{number}: unsupported or duplicate key')
        seen.add(name)
        def parent(reference: re.Match[str]) -> str:
            if reference[1] not in values:
                raise ValueError(f'repo.env:{number}: undefined parent')
            return values[reference[1]]
        value = re.sub(r'\$\{([A-Z][A-Z0-9_]*)\}', parent, value)
        if (len(value) > 4096 or any(char in value for char in '$`\\')
                or any(ord(char) < 32 or ord(char) == 127 for char in value)):
            raise ValueError(f'repo.env:{number}: unsupported data expansion')
        if name.startswith('DIR_'):
            if not (name == 'DIR_REPO_ROOT' and value == '.') and (
                    not re.fullmatch(r'[A-Za-z0-9_./@+-]+', value) or value.startswith('/')
                    or any(part in {'', '.', '..'} for part in value.split('/'))):
                raise ValueError(f'repo.env:{number}: unsafe repository root')
        elif name == 'REPOSITORY_FAMILIES':
            if value != 'desktop server':
                raise ValueError('repo.env: unsupported repository families')
        elif name == 'REPOSITORY_NAME':
            if not re.fullmatch(r'[a-z0-9][a-z0-9-]*', value):
                raise ValueError('repo.env: invalid repository name')
        elif not re.fullmatch(r'[A-Za-z0-9_./@+:,; -]*', value):
            raise ValueError('repo.env: invalid selection data')
        values[name] = value
    if seen != supported:
        raise ValueError('repo.env: missing supported key')
    return values


def merge_debconf(documents: list[tuple[str, str]]) -> list[str]:
    """Stable union of declared list answers; scalar overrides retain owner/type.

    Sources are already in declared precedence order. A different scalar owner
    or type is rejected; same-owner later values implement d-i include semantics.
    The seen pseudo-type is an independent record, not a replacement value.
    """
    records, order = {}, []
    for source, text in documents:
        pending = ''
        for line in text.splitlines():
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            pending += line.lstrip() if pending else line
            if pending.endswith(' \\'):
                pending = pending[:-1]
                continue
            fields = pending.split(None, 3)
            pending = ''
            if len(fields) < 3:
                raise ValueError(source + ': malformed debconf record')
            owner, question, kind = fields[:3]
            value = fields[3] if len(fields) == 4 else ''
            key = (question, kind == 'seen')
            if key not in records:
                order.append(key)
            else:
                previous = records[key]
                if previous[:2] != (owner, kind):
                    raise ValueError(source + ': conflicting debconf owner/type: ' + question)
                if question in LIST_FIELDS and kind != 'seen':
                    value = ' '.join(dict.fromkeys((previous[2] + ' ' + value).split()))
            records[key] = (owner, kind, value)
        if pending:
            raise ValueError(source + ': incomplete continuation')
    return [f'{records[key][0]} {key[0]} {records[key][1]} {records[key][2]}'.rstrip()
            for key in order]


def compile_profiles(sources: dict[str, bytes], selection: dict, suite: str,
                     suite_runtime: dict[str, str]) -> dict[str, bytes]:
    outputs = {}
    for profile in selection['profiles']:
        family = profile['family']
        shared_name = 'shared-de.env' if family == 'desktop' else 'shared-srv.env'
        parts = [f'suites/{suite}/runtime.env', 'hosts/installer/runtime.env:directories',
                 'hosts/installer/zram.env', f'hosts/profiles/{family}/{shared_name}',
                 profile['source'], 'hosts/profiles/shared.env', 'hosts/installer/identity.env',
                 'hosts/installer/runtime.env:files', 'hosts/installer/apparmor.env',
                 'hosts/logging/observability.env', 'hosts/installer/layout.env',
                 f'hosts/installer/{profile["filesystem"]}.env', 'hosts/installer/boot.env']
        values, provenance = {}, {}
        for part in parts:
            name, separator, section = part.partition(':')
            text = sources[name].decode()
            if separator:
                # One authored runtime contract: canonical directories are
                # available to normal profile ${DIR_*} references. Concrete
                # files that depend on profile policy follow profile data.
                # Blank omitted lines keep diagnostics at their source line.
                directories = section == 'directories'
                text = '\n'.join(line if line.startswith('DIR_') == directories else ''
                                 for line in text.splitlines()) + '\n'
            assignment_data(text, values, provenance, name, defaults_only=name in {'hosts/profiles/shared.env', 'hosts/installer/identity.env', 'hosts/installer/boot.env'})
        # Suite ownership is immutable even when preserved profile data names a
        # former build target. It does not alter vendor archive channel labels.
        for name, value in suite_runtime.items():
            values[name] = value
            provenance[name] = f'suites/{suite}/runtime.env'
        for name in ('CRYPTO_LUKS2_ROOT', 'CRYPTO_LUKS2_HOME', 'WIFI_ENABLE', 'IPV6_ENABLE', 'TIMESHIFT_ENABLE', 'SSH_SERVER_ENABLE'):
            if values.get(name) not in {'true', 'false'}:
                raise ValueError(profile['id'] + ': ' + name + ' requires an explicit boolean')
        for name in ('PARTMAN_CEILING_ENABLE', 'PARTMAN_REUSE_ENABLE'):
            if values.get(name) not in {'true', 'false'}:
                raise ValueError(profile['id'] + ': ' + name + ' requires an explicit boolean')
        for name, maximum in (('PARTMAN_CEILING_MB', 2147483647), ('PARTMAN_REUSE_START', 128)):
            value = values.get(name, '')
            if re.fullmatch(r'[1-9][0-9]{0,9}', value) is None or int(value) > maximum:
                raise ValueError(profile['id'] + ': invalid positive partition policy: ' + name)
        for name in ('HARDWARE_CPU_SCHEDULER_SCX_ENABLE',):
            if values.get(name) not in {'true', 'false'}:
                raise ValueError(profile['id'] + ': ' + name + ' requires an explicit boolean')
        if values.get('HARDWARE_CPU_SCHEDULER_SCX_MODE') not in {'direct', 'on-demand'}:
            raise ValueError(profile['id'] + ': invalid sched_ext activation mode')
        for name in ('HARDWARE_CPU_SCHEDULER_SCX_WORKER_NORMAL',
                     'HARDWARE_CPU_SCHEDULER_SCX_WORKER_PERFORMANCE'):
            worker = values.get(name, '')
            if re.fullmatch(r'scx_[a-z0-9_]{1,31}', worker) is None:
                raise ValueError(profile['id'] + ': invalid sched_ext worker name: ' + name)
        if (values['HARDWARE_CPU_SCHEDULER_SCX_WORKER_NORMAL']
                == values['HARDWARE_CPU_SCHEDULER_SCX_WORKER_PERFORMANCE']):
            raise ValueError(profile['id'] + ': sched_ext normal and performance workers must differ')
        interfaces = [values.get('MANAGED_NETWORK_ETHERNET_IFACE', 'eth0'),
                      values.get('MANAGED_NETWORK_WIFI_IFACE', 'wifi0')]
        if len(set(interfaces)) != 2 or any(re.fullmatch(r'[a-zA-Z0-9_-]{1,15}', name) is None for name in interfaces):
            raise ValueError(profile['id'] + ': invalid or overlapping managed interfaces')
        if values.get('MANAGED_NETWORK_PRIMARY_IFACE') not in interfaces:
            raise ValueError(profile['id'] + ': primary interface must be the managed Ethernet or Wi-Fi interface')
        for key in ('NFS_SERVER_ENABLE', 'NFS_CLIENT_ENABLE', 'NFS_CLIENT_READ_ONLY',
                    'FILEN_CLI_PRIV_ENABLE', 'FILEN_CLI_OFFSEC_ENABLE',
                    'HARDWARE_TUNING_AUTOSTART_ENABLE', 'HARDWARE_INTEL_CPU_TUNING_ENABLE',
                    'HARDWARE_NVIDIA_GPU_TUNING_ENABLE'):
            if values.get(key) not in {'true', 'false'}:
                raise ValueError(profile['id'] + ': ' + key + ' requires an explicit boolean')
        if family == 'desktop':
            for field in ('SYSTEMD_MEMORY_LOW_DESKTOP_ANCESTRY', 'SYSTEMD_MEMORY_LOW_USER_SESSION',
                          'SYSTEMD_MEMORY_LOW_USER_APP', 'SYSTEMD_BUILD_MEMORY_HIGH',
                          'SYSTEMD_BUILD_MEMORY_MAX', 'SYSTEMD_BUILD_MEMORY_SWAP_MAX'):
                if re.fullmatch(r'[1-9][0-9]?%|100%', values.get(field, '')) is None:
                    raise ValueError(profile['id'] + ': desktop resource policy requires 1..100 percent: ' + field)
            if int(values['SYSTEMD_BUILD_MEMORY_HIGH'][:-1]) >= int(values['SYSTEMD_BUILD_MEMORY_MAX'][:-1]):
                raise ValueError(profile['id'] + ': build MemoryHigh must be below MemoryMax')
            for field in ('SYSTEMD_BUILD_CPU_WEIGHT', 'SYSTEMD_BUILD_IO_WEIGHT', 'SYSTEMD_BUILD_TASKS_MAX'):
                value = values.get(field, '')
                if re.fullmatch(r'[1-9][0-9]{0,4}', value) is None or int(value) > 10000:
                    raise ValueError(profile['id'] + ': invalid desktop build resource policy: ' + field)
            for field in ('LABWC_WORKSPACE_COUNT_INTERNAL', 'LABWC_WORKSPACE_COUNT_EXTERNAL'):
                if re.fullmatch(r'[1-9]|1[0-2]', values.get(field, '')) is None:
                    raise ValueError(profile['id'] + ': ' + field + ' must be an integer in 1..12')
            if 'LABWC_WORKSPACE_COUNT' in values:
                raise ValueError(profile['id'] + ': use explicit internal and external workspace counts')
        work_pages = values.get('ZRAM_EMERGENCY_WORK_MAX_PAGES', '')
        pressure_pages = values.get('ZRAM_PRESSURE_WORK_MAX_PAGES', '')
        pass_pages = values.get('ZRAM_WRITEBACK_PASS_PAGES_MAX', '')
        if (re.fullmatch(r'[1-9][0-9]{0,6}', work_pages) is None
                or re.fullmatch(r'[1-9][0-9]{0,6}', pressure_pages) is None
                or re.fullmatch(r'[1-9][0-9]{0,6}', pass_pages) is None
                or not int(work_pages) <= int(pressure_pages) <= int(pass_pages) <= 4194304):
            raise ValueError(profile['id'] + ': invalid aggregate zram emergency work bound')
        if family == 'server':
            if values.get('CODEX_ONLY_ENABLE') not in {'true', 'false'}:
                raise ValueError(profile['id'] + ': CODEX_ONLY_ENABLE requires an explicit boolean')
            for field in ('WHISPER_ENABLE', 'LLAMA_ENABLE'):
                if values.get(field) not in {'true', 'false'}:
                    raise ValueError(profile['id'] + ': ' + field + ' requires an explicit boolean')
            if values.get('PODMAN_ROOTLESS_STATE_BASE') != '/pool/podman':
                raise ValueError(profile['id'] + ': Podman rootless state must remain under /pool/podman')
            for provider, uid in (('GITHUB', '2101'), ('GITLAB', '2102')):
                expected_user = 'ci-' + provider.lower()
                if values.get('PODMAN_' + provider + '_USER') != expected_user:
                    raise ValueError(profile['id'] + ': Podman ' + provider + ' user must be ' + expected_user)
                if values.get('PODMAN_' + provider + '_GROUP') != expected_user:
                    raise ValueError(profile['id'] + ': Podman ' + provider + ' group must match its user')
                driver = values.get('PODMAN_' + provider + '_STORAGE_DRIVER', '')
                if driver not in {'overlay', 'btrfs'}:
                    raise ValueError(profile['id'] + ': invalid Podman storage driver for ' + provider)
                for field in ('GRAPHROOT', 'IMAGE_COPY_TMP_DIR'):
                    value = values.get('PODMAN_' + provider + '_' + field, '')
                    if not value.startswith('/pool/podman/') or '..' in value or '//' in value:
                        raise ValueError(profile['id'] + ': Podman ' + provider + ' ' + field + ' must remain under /pool/podman')
                runroot = values.get('PODMAN_' + provider + '_RUNROOT', '')
                if runroot != '/run/user/' + uid + '/containers':
                    raise ValueError(profile['id'] + ': Podman ' + provider + ' runroot must be its private runtime path')
            if values.get('PODMAN_DEVOPS_STORAGE_DRIVER') not in {'overlay', 'btrfs'}:
                raise ValueError(profile['id'] + ': invalid Podman DevOps storage driver')
            if (values.get('PODMAN_DEVOPS_USER') != 'srv-devops'
                    or values.get('PODMAN_DEVOPS_GROUP') != 'srv-devops'):
                raise ValueError(profile['id'] + ': Podman DevOps identity must be srv-devops:srv-devops')
            for field in ('PODMAN_DEVOPS_GRAPHROOT_ROOT', 'PODMAN_DEVOPS_IMAGE_COPY_TMP_ROOT'):
                value = values.get(field, '')
                if value != '/pool/podman/devops':
                    raise ValueError(profile['id'] + ': Podman DevOps ' + field + ' must use /pool/podman/devops')
            if values.get('PODMAN_DEVOPS_RUNROOT_BASE') != '/run/user':
                raise ValueError(profile['id'] + ': Podman DevOps runroot base must be /run/user')
            for field, maximum in (('PODMAN_SERVICE_CPU_WEIGHT', 10000),
                                   ('PODMAN_SERVICE_IO_WEIGHT', 10000),
                                   ('PODMAN_SERVICE_TASKS_MAX', 65536)):
                value = values.get(field, '')
                if not value.isdecimal() or not 1 <= int(value) <= maximum:
                    raise ValueError(profile['id'] + ': invalid Podman service resource policy ' + field)
            for field in ('PODMAN_SERVICE_MEMORY_HIGH', 'PODMAN_SERVICE_MEMORY_MAX'):
                if re.fullmatch(r'[1-9][0-9]?%|100%', values.get(field, '')) is None:
                    raise ValueError(profile['id'] + ': invalid Podman service memory policy ' + field)
            if 'DEVOPS_CODEX_TOOLS_ENABLE' in values:
                raise ValueError(profile['id'] + ': replace DEVOPS_CODEX_TOOLS_ENABLE with CODEX_ONLY_ENABLE')
            for field, maximum in (('CI_RUNNER_CPU_WEIGHT', 10000), ('CI_RUNNER_IO_WEIGHT', 10000), ('CI_RUNNER_TASKS_MAX', 65536)):
                value = values.get(field, '')
                minimum = 64 if field == 'CI_RUNNER_TASKS_MAX' else 1
                if not value.isdecimal() or not minimum <= int(value) <= maximum:
                    raise ValueError(profile['id'] + ': invalid server workload resource policy ' + field)
            memory = []
            for field in ('CI_RUNNER_MEMORY_HIGH', 'CI_RUNNER_MEMORY_MAX'):
                value = values.get(field, '')
                if re.fullmatch(r'[1-9][0-9]?%|100%', value) is None:
                    raise ValueError(profile['id'] + ': workload memory policy requires a percentage')
                memory.append(int(value[:-1]))
            if memory[0] >= memory[1]:
                raise ValueError(profile['id'] + ': workload MemoryHigh must be below MemoryMax')
        if values.get('INCUS_WEB_UI_ENABLE') not in {'true', 'false'}:
            raise ValueError(profile['id'] + ': explicit Incus Web UI policy is required')
        if family == 'server' and values['INCUS_WEB_UI_ENABLE'] != 'false':
            raise ValueError(profile['id'] + ': headless server roles cannot request desktop Incus Web UI integration')
        nfs_interfaces = values.get('NFS_INTERFACES', '').split()
        if (not nfs_interfaces or len(set(nfs_interfaces)) != len(nfs_interfaces)
                or not set(nfs_interfaces) <= set(interfaces)):
            raise ValueError(profile['id'] + ': NFS interfaces must name only the selected physical uplinks')
        nfs_port = values.get('NFS_SERVER_PORT', '')
        if not nfs_port.isdecimal() or not 1024 <= int(nfs_port) <= 65535:
            raise ValueError(profile['id'] + ': invalid NFS service port')
        if values['TIMESHIFT_ENABLE'] == 'true' and profile['filesystem'] != 'btrfs':
            raise ValueError(profile['id'] + ': TIMESHIFT_ENABLE=true requires a Btrfs profile')
        values['SNAPSHOTS_POLICY'] = 'timeshift-btrfs' if values['TIMESHIFT_ENABLE'] == 'true' else 'none'
        provenance['SNAPSHOTS_POLICY'] = profile['source'] + ':TIMESHIFT_ENABLE'
        if values['TIMESHIFT_ENABLE'] == 'true':
            for name in ('DAILY', 'WEEKLY', 'MONTHLY'):
                count = values.get('TIMESHIFT_COUNT_' + name, '')
                if not count.isdecimal() or not 0 <= int(count) <= 100:
                    raise ValueError(profile['id'] + ': invalid Timeshift retention')
                calendar = values.get('TIMESHIFT_' + name + '_CALENDAR', '')
                if re.fullmatch(r'[A-Za-z0-9*, :/.-]{1,120}', calendar) is None:
                    raise ValueError(profile['id'] + ': invalid Timeshift calendar')
        if family == 'server':
            for key, version in (('SSH_SERVER_CIDR_ALLOW', 4), ('SSH_SERVER_CIDR_ALLOW6', 6)):
                network = ipaddress.ip_network(values[key], strict=True)
                if network.version != version or network.prefixlen == 0 or network.is_multicast:
                    raise ValueError(profile['id'] + ': invalid SSH source ACL')
            values['LABWC_DESKTOP_ENABLE'] = 'false'
            provenance['LABWC_DESKTOP_ENABLE'] = 'role-family/server'
        prefix = f'catalog/compiled/{suite}/profiles/{family}/{profile["id"]}'
        if any("'" in value for value in values.values()):
            raise ValueError('public compiled profile contains an unsupported literal quote')
        lines, previous_owner = ['# Compiled non-secret profile data; never source as shell.\n'], None
        for name, value in values.items():
            owner = provenance[name].rsplit(':', 1)[0]
            if owner != previous_owner:
                lines.append('\n# Policy owner: ' + owner + '\n')
                previous_owner = owner
            lines.append(f"{name}='{value}'\n")
        outputs[prefix + '.env'] = ''.join(lines).encode()
        outputs[prefix + '.provenance.json'] = encode(provenance)
        account_values, account_provenance = {}, {}
        assignment_data(sources['hosts/installer/account.env'].decode(), account_values,
                        account_provenance, 'hosts/installer/account.env')
        for field in tuple(account_values):
            if field in values:
                if field in {'FRUUX_CALENDAR_USERNAME', 'FRUUX_CALENDAR_PASSWORD',
                             'ACCOUNT_USERNAME', 'ACCOUNT_PASSWORD', 'ACCOUNT_PASSWORD_HASH'} and values[field]:
                    raise ValueError(profile['id'] + ': private identity or credentials cannot be public profile policy')
                account_values[field] = values[field]
        account_lines = ['# Compiled non-secret account policy; parse as restricted data.\n']
        for field, value in account_values.items():
            # This is one literal quoting grammar, shared with effective private
            # snapshots. The d-i AWK decoder consumes it without shell sourcing.
            literal = "'" + value.replace("'", "'\\''") + "'"
            account_lines.append(field + '=' + literal + '\n')
        outputs[prefix + '.account.env'] = ''.join(account_lines).encode()

        if family == 'server':
            outputs[prefix + '.artifacts.json'] = encode(compile_server_artifacts(values))
    return outputs


def compile_runner_policy(values: dict[str, str]) -> dict:
    """Publish non-secret runner and job defaults from shared/host profiles."""
    trust = values.get('CI_RUNNER_JOB_TRUST')
    if trust != 'dedicated-private-project;protected-refs;no-public-forks':
        raise ValueError('persistent runners require the explicit trusted-project policy')
    result = {}
    for provider in ('github', 'gitlab'):
        url = values.get('CI_' + provider.upper() + '_URL', '')
        if url:
            parsed = urlsplit(url)
            if (len(url) > 2048 or any(not 33 <= ord(value) <= 126 for value in url)
                    or parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password
                    or parsed.port not in (None, 443) or parsed.query or parsed.fragment
                    or re.fullmatch(r'(?:/[A-Za-z0-9_.~-]+)*/?', parsed.path) is None
                    or any(part in ('.', '..') for part in parsed.path.split('/'))):
                raise ValueError('invalid public runner enrollment URL: ' + provider)
        result[provider + ('-actions' if provider == 'github' else '-cicd')] = {'url': url, 'job_trust': trust}
    gitlab = result['gitlab-cicd']
    suite = values['TARGET_SUITE'].upper()
    image = values.get('CI_GITLAB_RUNNER_IMAGE') or values['CI_GITLAB_RUNNER_IMAGE_' + suite]
    helpers = {}
    for architecture in ('AMD64', 'ARM64'):
        helper = values.get('CI_GITLAB_RUNNER_HELPER_IMAGE_' + architecture, '')
        helpers[architecture.lower()] = helper
    for value in (image, *helpers.values()):
        if not value:
            continue
        if (len(value) > 512 or re.fullmatch(r'[a-zA-Z0-9._/:+-]+(?:@sha256:[0-9a-f]{64})?', value) is None
                or '//' in value or any(part in ('.', '..') for part in value.split('/'))):
            raise ValueError('invalid operator-selected runner image reference')
    executor = values.get('CI_GITLAB_RUNNER_EXECUTOR')
    pull = values.get('CI_GITLAB_RUNNER_PULL_POLICY')
    helper_flavor = values.get('CI_GITLAB_RUNNER_HELPER_FLAVOR')
    if helper_flavor != 'ubuntu' or any(not helper for helper in helpers.values()):
        raise ValueError('GitLab requires an explicit Debian-derived helper image and Ubuntu native helper flavor')
    if executor != 'docker' or pull not in {'if-not-present', 'always'}:
        raise ValueError('GitLab requires its explicit rootless Docker-compatible executor and pull policy')
    podman_sockets = {}
    for provider, uid in (('GITHUB', '2101'), ('GITLAB', '2102')):
        runtime = values.get('PODMAN_' + provider + '_RUNTIME_DIR', '')
        socket = values.get('PODMAN_' + provider + '_SOCKET', '')
        expected_runtime = '/run/user/' + uid
        expected_socket = expected_runtime + '/podman/podman.sock'
        if runtime != expected_runtime or socket != expected_socket:
            raise ValueError(provider + ' rootless runtime/socket policy is not its private systemd user path')
        podman_sockets[provider.lower()] = socket
    result['github-actions']['podman_socket'] = podman_sockets['github']
    gitlab.update(executor=executor, pull_policy=pull, default_image=image,
                  helper_images=helpers, helper_flavor=helper_flavor,
                  podman_socket=podman_sockets['gitlab'])
    bazel = {}
    for key, field, schemes in (
            ('CI_BAZEL_REMOTE_CACHE_URL', 'remote_cache', {'https', 'grpcs'}),
            ('CI_BUILDBUDDY_BES_BACKEND', 'bes_backend', {'grpcs'}),
            ('CI_BUILDBUDDY_RESULTS_URL', 'bes_results_url', {'https'})):
        value = values.get(key, '')
        parsed = urlsplit(value)
        if value and (len(value) > 2048 or parsed.scheme not in schemes or not parsed.hostname
                      or parsed.username or parsed.password or parsed.query or parsed.fragment
                      or any(ord(character) < 33 or ord(character) > 126 for character in value)):
            raise ValueError('invalid public CI Bazel/BuildBuddy endpoint: ' + key)
        bazel[field] = value
    for policy in result.values():
        policy['bazel'] = bazel
    return result


def compile_server_artifacts(values: dict[str, str]) -> dict:
    """Serialize server artifact policy from the selected profile's env data.

    This function owns only the target JSON shape. Versions, URLs, hashes,
    redirect hosts and extraction bounds have one authored owner: shared-srv.env
    and an explicit host override. There is no second authored download catalog.
    """
    result = {}
    prefixes = {'github-actions': 'CI_GITHUB_RUNNER', 'gitlab-cicd': 'CI_GITLAB_RUNNER',
                'technitium': 'TECHNITIUM', 'dotnet': 'TECHNITIUM_DOTNET',
                'bazelisk': 'DEVOPS_BAZELISK', 'buildbuddy': 'DEVOPS_BUILDBUDDY'}
    for name, prefix in prefixes.items():
        def field(suffix):
            key = prefix + '_' + suffix
            if key not in values:
                raise ValueError('missing server artifact policy: ' + key)
            return values[key]
        kind, entry = field('KIND'), safe_path(field('ENTRY'))
        if kind not in {'tar', 'elf', 'file'}:
            raise ValueError(prefix + ': invalid artifact kind')
        version, source = field('VERSION'), field('SOURCE_URL')
        if re.fullmatch(r'[a-zA-Z0-9_.+-]{1,120}', version) is None:
            raise ValueError(prefix + ': invalid immutable version identity')
        source_url = urlsplit(source)
        if source_url.scheme != 'https' or not source_url.hostname or source_url.username or source_url.password:
            raise ValueError(prefix + ': invalid source evidence URL')
        hosts = field('ARTIFACT_HOSTS').split()
        if not hosts or len(hosts) > 16 or len(set(hosts)) != len(hosts) or any(
                re.fullmatch(r'[a-z0-9]+(?:[.-][a-z0-9]+)*', host) is None for host in hosts):
            raise ValueError(prefix + ': invalid redirect host policy')
        limits = {}
        for suffix, key, maximum in [('EXPANDED_BYTES', 'expanded_bytes', 4294967296),
                                     ('MAXIMUM_MEMBERS', 'maximum_members', 100000)]:
            value = field(suffix)
            if not value.isdecimal() or not 1 <= int(value) <= maximum:
                raise ValueError(prefix + ': invalid artifact extraction bound')
            limits[key] = int(value)
        links = field('RELATIVE_LINK_PREFIXES').split()
        for link in links:
            if not link.endswith('/'):
                raise ValueError(prefix + ': symlink prefix must name a directory')
            safe_path(link[:-1])
        architectures = {}
        arches = field('ARCHITECTURES').split()
        if not arches or len(set(arches)) != len(arches) or any(arch not in {'amd64', 'arm64'} for arch in arches):
            raise ValueError(prefix + ': invalid artifact architectures')
        for arch in arches:
            url = field('URL_' + arch.upper())
            parsed = urlsplit(url)
            if (parsed.scheme != 'https' or parsed.hostname not in hosts or parsed.username or parsed.password
                    or parsed.port not in (None, 443) or parsed.fragment or '/latest/' in parsed.path):
                raise ValueError(prefix + ': artifact URL violates pinned acquisition policy')
            algorithm = field('DIGEST_ALGORITHM')
            if algorithm not in {'sha256', 'sha512'}:
                raise ValueError(prefix + ': invalid digest algorithm')
            digest = field(algorithm.upper() + '_' + arch.upper())
            if re.fullmatch(r'[a-f0-9]{' + str(64 if algorithm == 'sha256' else 128) + '}', digest) is None:
                raise ValueError(prefix + ': invalid artifact digest')
            architectures[arch] = {'url': url, algorithm: digest}
        result[name] = {'version': version, 'source': source, 'hosts': hosts, **limits,
                        'relative_link_prefixes': links, 'architectures': architectures,
                        'kind': kind, 'entry': entry}
    reviewed = values.get('ARTIFACTS_REVIEWED', '')
    if re.fullmatch(r'20[0-9]{2}-[0-9]{2}-[0-9]{2}', reviewed) is None:
        raise ValueError('server artifact review date is missing')
    # Profile-controlled native packages are independent of selected server
    # roles. Their bytes are pinned by the profile URL and digest; transport
    # size ceilings are deliberately not part of this acquisition contract.
    packages = {}
    enabled = values.get('HARDWARE_CPU_SCHEDULER_SCX_ENABLE')
    if enabled not in {'true', 'false'}:
        raise ValueError('server scheduler enable policy must be boolean')
    if enabled == 'true':
        hosts = values['HARDWARE_CPU_SCHEDULER_SCX_ARTIFACT_HOSTS'].split()
        if (not hosts or len(set(hosts)) != len(hosts) or len(hosts) > 16
                or any(re.fullmatch(r'[a-z0-9]+(?:[.-][a-z0-9]+)*', host) is None for host in hosts)):
            raise ValueError('invalid server scheduler host policy')
        for name, prefix in [('scx', 'HARDWARE_CPU_SCHEDULER_SCX_PACKAGE'),
                             ('scx-loader', 'HARDWARE_CPU_SCHEDULER_SCX_LOADER_PACKAGE')]:
            url, digest = values[prefix + '_URL'], values[prefix + '_SHA256']
            parsed = urlsplit(url)
            if (parsed.scheme != 'https' or parsed.hostname not in hosts or parsed.username or parsed.password
                    or parsed.port not in (None, 443) or parsed.fragment or '/latest/' in parsed.path
                    or re.fullmatch(r'[a-f0-9]{64}', digest) is None):
                raise ValueError('invalid pinned server scheduler artifact')
            packages[name] = {'hosts': hosts,
                              'architectures': {'amd64': {'url': url, 'sha256': digest}}}
    devops = {}
    for key, minimum, maximum in (
        ('DEVOPS_BAZEL_SERVER_IDLE_SECONDS', 60, 86400),
        ('DEVOPS_BAZEL_REPOSITORY_DOWNLOADER_RETRIES', 0, 10),
        ('DEVOPS_BUILDBUDDY_HTTP_PORT', 1024, 65535),
        ('DEVOPS_BUILDBUDDY_GRPC_PORT', 1024, 65535),
        ('DEVOPS_BUILDBUDDY_CACHE_BYTES', 1048576, 1000000000000),
        ('DEVOPS_BUILDBUDDY_STORAGE_TTL_SECONDS', 3600, 31536000)):
        value = values.get(key, '')
        if not value.isdecimal() or not minimum <= int(value) <= maximum:
            raise ValueError('invalid headless DevOps policy: ' + key)
        devops[key] = int(value)
    if devops['DEVOPS_BUILDBUDDY_HTTP_PORT'] == devops['DEVOPS_BUILDBUDDY_GRPC_PORT']:
        raise ValueError('local BuildBuddy HTTP and gRPC ports must differ')
    devops['toolchains'] = {}
    for key in ('CI_C_COMPILER', 'CI_CPP_COMPILER', 'CI_LLVM_COMPILER', 'CI_RUST_COMPILER',
                'CI_RUST_PACKAGE_MANAGER', 'CI_RUST_COMPILER_WRAPPER', 'CI_GO_COMPILER',
                'CI_PYTHON_INTERPRETER', 'CI_NODE_INTERPRETER', 'CI_JAVA_RUNTIME',
                'CI_RUBY_INTERPRETER', 'CI_PERL_INTERPRETER', 'CI_ANSIBLE_BINARY', 'CI_BAZEL_BINARY'):
        value = values.get(key, '')
        if re.fullmatch(r'[a-zA-Z0-9_+-]{1,40}', value) is None:
            raise ValueError('invalid native toolchain command name: ' + key)
        devops['toolchains'][key] = value
    dns = {}
    for field in ('PROJECT', 'INSTANCE', 'POOL', 'BRIDGE', 'VETH'):
        value = values.get('TECHNITIUM_INCUS_' + field, '')
        if re.fullmatch(r'[a-z][a-z0-9-]{0,14}', value) is None:
            raise ValueError('invalid private Incus DNS object identity')
        dns[field.lower()] = value
    if dns['bridge'] == values.get('INCUS_BRIDGE_NAME') or dns['veth'] in {
            values.get('MANAGED_NETWORK_ETHERNET_IFACE'), values.get('MANAGED_NETWORK_WIFI_IFACE')}:
        raise ValueError('private DNS veth/bridge collides with another network owner')
    for family in (4, 6):
        interface = ipaddress.ip_interface(values['TECHNITIUM_INCUS_IPV' + str(family) + '_CIDR'])
        address = ipaddress.ip_address(values['TECHNITIUM_INCUS_IPV' + str(family) + '_ADDRESS'])
        if (interface.version != family or address.version != family or not interface.ip.is_private
                or not address.is_private or interface.ip.is_loopback or interface.ip.is_link_local
                or address not in interface.network or address == interface.ip
                or address in (interface.network.network_address, interface.network.broadcast_address)
                or interface.network.prefixlen != (24 if family == 4 else 64)):
            raise ValueError('invalid private DNS guest address pair')
        dns['ipv' + str(family) + '_cidr'] = str(interface)
        dns['ipv' + str(family) + '_address'] = str(address)
    bootstrap = ipaddress.ip_address(values['TECHNITIUM_INCUS_BOOTSTRAP_DNS'])
    if bootstrap.version != 4 or not bootstrap.is_global:
        raise ValueError('DNS guest bootstrap resolver must be an explicit public IPv4 address')
    dns['bootstrap_dns'] = str(bootstrap)
    for field, minimum, maximum in (('MEMORY_MIB', 256, 32768), ('CPUS', 1, 64),
                                     ('PROCESSES', 64, 4096), ('DISK_GIB', 2, 64)):
        value = values['TECHNITIUM_INCUS_' + field]
        if not value.isdecimal() or not minimum <= int(value) <= maximum:
            raise ValueError('invalid DNS guest resource bound')
        dns[field.lower()] = int(value)
    dns['ipv6_enabled'] = values['IPV6_ENABLE'] == 'true'
    dns['suite'] = values['TARGET_SUITE']
    return {'format': 1, 'reviewed': reviewed, 'artifacts': result,
            'profile_packages': packages, 'devops': devops, 'dns_container': dns,
            'runners': compile_runner_policy(values)}


def class_dispatch(sources: dict[str, bytes], classes: dict[str, dict]) -> None:
    """Installer dispatch is separate from plain preseed class contents.

    Comments in .cfg files are never inspected for behavior. This one bounded
    table maps actual selected class names to installer helpers and constraints;
    it cannot introduce packages, repositories, aliases or synthetic features.
    """
    source = 'hooks/installer/class-dispatch.tsv'
    rows = sources[source].decode().splitlines()
    if not rows or rows[0] != 'format\t1' or len(rows) > 1000:
        raise ValueError(source + ': invalid dispatch format or record bound')
    declared, stage_owners = set(), set()
    for number, line in enumerate(rows[1:], 2):
        if not line or line.startswith('#'):
            continue
        cells = line.split('\t')
        if cells[0] not in {'class', 'stage'} or len(cells) != (5 if cells[0] == 'class' else 7):
            raise ValueError(f'{source}:{number}: malformed dispatch row')
        owners = cells[1].split(',')
        if not owners or len(set(owners)) != len(owners) or any(owner not in classes for owner in owners):
            raise ValueError(f'{source}:{number}: unknown or duplicate physical class owner')
        if cells[0] == 'class':
            arches, required, conflicts = (value.split(',') if value != '-' else [] for value in cells[2:])
            if not arches or any(arch not in {'amd64', 'arm64'} for arch in arches) or len(set(arches)) != len(arches):
                raise ValueError(f'{source}:{number}: invalid architecture constraint')
            if any(ref not in classes for ref in required + conflicts):
                raise ValueError(f'{source}:{number}: constraint names no physical class')
            if len(set(required + conflicts)) != len(required + conflicts):
                raise ValueError(f'{source}:{number}: duplicate or conflicting dependency')
            for owner in owners:
                if owner in declared or owner in required + conflicts:
                    raise ValueError(f'{source}:{number}: duplicate or self-referencing class constraint')
                declared.add(owner)
                classes[owner].update(architectures=list(arches), requires=list(required), conflicts=list(conflicts))
        else:
            name, phase, selector, after, before = cells[2:]
            if (phase not in PHASES or STAGE_IDENTIFIER.fullmatch(name) is None
                    or safe_path(selector) != selector
                    or re.fullmatch(r'[A-Za-z0-9_./@+-]+', selector) is None
                    or '__INSTALLER_' in selector):
                raise ValueError(f'{source}:{number}: invalid phase provider')
            after_ids, before_ids = (value.split(',') if value != '-' else [] for value in (after, before))
            if any(STAGE_IDENTIFIER.fullmatch(value) is None or value == name for value in after_ids + before_ids):
                raise ValueError(f'{source}:{number}: invalid stage ordering constraint')
            for owner in owners:
                if (owner, name) in stage_owners:
                    raise ValueError(f'{source}:{number}: duplicate stage owner')
                stage_owners.add((owner, name))
                classes[owner]['stages'].append({'id': name, 'phase': phase, 'selector': selector,
                                                'after': list(after_ids), 'before': list(before_ids)})


def package_records(text: str, source: str) -> list[str]:
    result = []
    for line in merge_debconf([(source, text)]):
        fields = line.split(None, 3)
        if fields[:3] == ['d-i', 'pkgsel/include', 'string']:
            for word in fields[3].split():
                if re.fullmatch(r'[a-z0-9][a-z0-9+.:~/-]*', word) is None:
                    raise ValueError(source + ': unsafe package token')
                if word not in result:
                    result.append(word)
    return result


def compose_class_answers(documents: list[tuple[str, str]]) -> list[str]:
    """Merge answers while keeping each source's APT slot block intact.

    Local slot numbers are source-local. Identical repositories coalesce only
    when their complete authentication and source policy agrees. Different
    repositories never overwrite each other because they used the same slot.
    """
    ordinary, repositories, repository_identity = [], [], {}
    for source, text in documents:
        plain, local = [], {}
        for line in merge_debconf([(source, text)]):
            fields = line.split(None, 3)
            match = re.fullmatch(r'apt-setup/local([0-9]+)/([a-z][a-z0-9-]*)', fields[1])
            if fields[0] == 'd-i' and match:
                slot, field = match.groups()
                local.setdefault(int(slot), {})[field] = (fields[2], fields[3] if len(fields) == 4 else '')
            else:
                plain.append(line)
        ordinary.append((source, '\n'.join(plain) + '\n'))
        for slot in sorted(local):
            record = local[slot]
            if 'repository' not in record:
                raise ValueError(source + ': APT block has no repository')
            identity = record['repository']
            # Human comments do not change the APT trust or package policy.
            policy = {key: value for key, value in record.items() if key != 'comment'}
            if identity in repository_identity:
                if repository_identity[identity] != policy:
                    raise ValueError(source + ': conflicting policy for one APT repository')
                continue
            repository_identity[identity] = policy
            repositories.append(record)
    result = merge_debconf(ordinary)
    for slot, record in enumerate(repositories):
        for field, (kind, value) in record.items():
            result.append(f'd-i apt-setup/local{slot}/{field} {kind} {value}'.rstrip())
    return result


def ordered_class_stages(records: list[dict]) -> list[dict]:
    stages = {}
    for record in records:
        for value in record['stages']:
            name = value['id']
            if name in stages:
                if stages[name] != value:
                    raise ValueError('class owners disagree on shared stage: ' + name)
                continue
            stages[name] = {**value, 'after': list(value['after'])}
    for name, value in stages.items():
        for successor in value['before']:
            if successor in stages:
                stages[successor]['after'].append(name)
    result, finished, helpers = [], set(), set()
    while len(finished) != len(stages):
        ready = []
        for name, value in stages.items():
            for dependency in value['after']:
                if dependency not in stages:
                    raise ValueError(name + ': missing class stage dependency ' + dependency)
                if PHASES[stages[dependency]['phase']] > PHASES[value['phase']]:
                    raise ValueError('class stage phase inversion')
            if name not in finished and set(value['after']) <= finished:
                ready.append(name)
        if not ready:
            raise ValueError('class stage cycle')
        name = min(ready, key=lambda x: (PHASES[stages[x]['phase']], x))
        value = stages[name]
        helper = (value['phase'], value['selector'])
        if helper in helpers:
            raise ValueError('class helper runs more than once in its phase')
        helpers.add(helper); finished.add(name); result.append(value)
    return result


def compile_classes(sources: dict[str, bytes]) -> tuple[dict[str, bytes], dict[str, bytes], dict]:
    """Capture the real suite class files; no parallel feature authority."""
    selection = read_json(sources, 'catalog/selection.json')
    outputs, graph, matrix = {}, [], []
    suite_classes = {}
    qualification_rows = [("format", "1")]
    qualifications_by_suite = {suite: {} for suite in ('forky', 'trixie')}
    policy = sources['hooks/installer/suite-policy.tsv'].decode()
    if len(policy) > 8192 or not policy.startswith('format\t1\n'):
        raise ValueError('invalid installer suite policy format or size')
    for line in policy.splitlines()[1:]:
        cells = line.split('\t')
        if len(cells) != 5:
            raise ValueError('installer suite policy requires five fields')
        suite, family, status, identifier, reason = cells
        if (suite not in qualifications_by_suite or family not in {'desktop', 'server'}
                or family in qualifications_by_suite[suite]
                or status not in {'blocked', 'source-candidate'}
                or IDENTIFIER.fullmatch(identifier) is None
                or re.fullmatch(r'[A-Za-z0-9 .;:/,()-]{1,320}', reason) is None):
            raise ValueError('invalid or ambiguous installer suite policy')
        qualifications_by_suite[suite][family] = {'status': status, 'id': identifier, 'reason': reason}
        qualification_rows.append(tuple(cells))
    for suite in ('forky', 'trixie'):
        classes = {}
        prefix = f'frontends/{suite}/classes/'
        for path, data in sorted(sources.items()):
            if not path.startswith(prefix) or not path.endswith('.cfg'):
                continue
            relative = path.removeprefix(prefix)
            if not relative.startswith(('class-select/', 'class-auto/', 'class-profile/')):
                continue
            ref = relative.split('/', 1)[1].removesuffix('.cfg')
            if relative.startswith('class-profile/'):
                ref = 'profile/' + ref
            safe_path(ref)
            if ref in classes:
                raise ValueError('ambiguous physical class: ' + ref)
            text = data.decode()
            family = ref.split('/')[1] if ref.startswith('role/') else 'all'
            if ref.startswith('profile/'):
                matches = [profile for profile in selection['profiles']
                           if profile['family'] + '/' + profile['id'] == ref.removeprefix('profile/')]
                if len(matches) != 1:
                    raise ValueError(path + ': profile class has no unique registered policy')
                family = matches[0]['family']
            if family not in {'all', 'desktop', 'server'}:
                raise ValueError(path + ': invalid role class directory')
            record = {'requires': [], 'conflicts': [], 'architectures': ['amd64'],
                      'family': family, 'stages': [], 'path': path, 'text': text,
                      'packages': package_records(text, path)}
            classes[ref] = record
        suite_classes[suite] = classes
        common_refs = ['common.cfg', 'fragments/network.cfg', 'fragments/partman.cfg', 'fragments/apt.cfg']
        for ref in [*common_refs, 'fragments/finish.cfg', 'fragments/ssh.cfg',
                    'fragments/timeshift.cfg', 'fragments/codex.cfg',
                    'fragments/whisper.cfg', 'fragments/llama.cfg']:
            path = f'frontends/{suite}/{ref}'
            text = sources[path].decode()
            classes[ref] = {'requires': [], 'conflicts': [], 'architectures': ['amd64'],
                            'family': 'all', 'stages': [], 'path': path, 'text': text,
                            'packages': package_records(text, path)}
        class_dispatch(sources, classes)
        qualifications = qualifications_by_suite[suite]
        if set(qualifications) != {'desktop', 'server'}:
            raise ValueError('suite qualification must cover both role families')
        suite_runtime, suite_provenance = {}, {}
        runtime_name = f'suites/{suite}/runtime.env'
        assignment_data(sources[runtime_name].decode(), suite_runtime, suite_provenance, runtime_name)
        if (set(suite_runtime) != {'TARGET_SUITE', 'GITBUILD_DISTRIBUTION', 'GITBUILD_DEFAULT_SUITE'}
                or any(value != suite for value in suite_runtime.values())):
            raise ValueError(runtime_name + ': suite-owned runtime fields must match the frontend')
        outputs.update(compile_profiles(sources, selection, suite, suite_runtime))
        for ref, record in sorted(classes.items()):
            for required in record['requires'] + record['conflicts']:
                if required not in classes:
                    raise ValueError(ref + ': required/conflicting class does not exist')
            graph.append(('class', suite, ref, ','.join(record['requires']), ','.join(record['conflicts']),
                          ','.join(record['architectures']), record['family']))
            graph += [('pkg', suite, ref, package) for package in record['packages']]
            for answer in merge_debconf([(record['path'], record['text'])]):
                cells = answer.split(None, 3)
                if len(cells) == 3:
                    cells.append('')
                if any('\t' in cell or '\n' in cell or '\r' in cell for cell in cells):
                    raise ValueError(record['path'] + ': answer contains a tab or control separator')
                graph.append(('answer', suite, ref, *cells))
            for stage in record['stages']:
                graph.append(('stage', suite, ref, stage['id'], stage['phase'], stage['selector'],
                              ','.join(stage['after']), ','.join(stage['before'])))
        desktop = sorted(ref for ref in classes if ref.startswith('role/desktop/'))
        server = sorted(ref for ref in classes if ref.startswith('role/server/'))
        selections = [(ref,) for ref in desktop]
        selections += [refs for count in range(1, len(server) + 1) for refs in combinations(server, count)]
        for refs in selections:
            if any(set(classes[ref]['conflicts']).intersection(refs) for ref in refs):
                # Unsupported combinations have no installable plan. The
                # same physical-class conflict table drives early d-i rejection.
                continue
            family = refs[0].split('/')[1]
            profile_id = 'btrfs-de' if family == 'desktop' else 'btrfs-srv-flex'
            selected_refs = ['site/lab', *refs, 'arch/amd64', 'cpu/intel', 'kernel/x64v2', 'gpu/generic',
                             'network/dhcp', 'disk/nvme', 'profile/' + family + '/' + profile_id]
            profile_values, profile_provenance = {}, {}
            compiled_profile = f'catalog/compiled/{suite}/profiles/{family}/{profile_id}.env'
            assignment_data(outputs[compiled_profile].decode(), profile_values, profile_provenance,
                            compiled_profile, literals=True)
            if family == 'desktop' and profile_values['SSH_SERVER_ENABLE'] == 'true':
                selected_refs.append('fragments/ssh.cfg')
            if profile_values['TIMESHIFT_ENABLE'] == 'true':
                selected_refs.append('fragments/timeshift.cfg')
            codex_only = profile_values.get('CODEX_ONLY_ENABLE', 'false') if family == 'server' else 'false'
            codex_enabled = codex_only == 'true' or any(ref in refs for ref in (
                'role/desktop/medium', 'role/desktop/full', 'role/server/devops'))
            if codex_enabled:
                selected_refs.append('fragments/codex.cfg')
            whisper_enable = profile_values.get('WHISPER_ENABLE', 'false') if family == 'server' else 'false'
            llama_enable = profile_values.get('LLAMA_ENABLE', 'false') if family == 'server' else 'false'
            if family == 'server':
                for field, value in (('WHISPER_ENABLE', whisper_enable), ('LLAMA_ENABLE', llama_enable)):
                    if value not in {'true', 'false'}:
                        raise ValueError(profile_id + ': ' + field + ' requires an explicit boolean')
            if whisper_enable == 'true':
                selected_refs.append('fragments/whisper.cfg')
            if llama_enable == 'true':
                selected_refs.append('fragments/llama.cfg')
            records = [classes[ref] for ref in [*common_refs, *selected_refs, 'fragments/finish.cfg']]
            role_records = [classes[ref] for ref in refs]
            roles = [ref.removeprefix('role/') for ref in refs]
            identity = family + '/' + '+'.join(role.split('/')[1] for role in roles)
            packages = []
            for ref, record in zip(refs, role_records):
                if record['family'] != family:
                    raise ValueError(ref + ': role/family disagreement')
                if family == 'server' and 'openssh-server' not in record['packages']:
                    raise ValueError(ref + ': server class itself must include openssh-server')
                for package in ('crowdsec',):
                    if package not in record['packages']:
                        raise ValueError(ref + ': missing required role package ' + package)
            for record in records:
                packages.extend(record['packages'])
            packages = list(dict.fromkeys(packages))
            stages = ordered_class_stages(records)
            stage_ids = {stage['id'] for stage in stages}
            answers = compose_class_answers([(record['path'], record['text']) for record in records])
            profile_policy = {
                'ssh_enable': profile_values['SSH_SERVER_ENABLE'],
                'ssh_port': profile_values['SSH_SERVER_PORT'],
                'crypto_root': profile_values['CRYPTO_LUKS2_ROOT'],
                'crypto_home': profile_values['CRYPTO_LUKS2_HOME'],
                'wifi_enable': profile_values['WIFI_ENABLE'],
                'primary_iface': profile_values['MANAGED_NETWORK_PRIMARY_IFACE'],
                'ipv6_enable': profile_values['IPV6_ENABLE'],
                'snapshots': profile_values['SNAPSHOTS_POLICY'],
                'timeshift_enable': profile_values['TIMESHIFT_ENABLE'],
                'codex_only_enable': codex_only,
                'codex_enable': 'true' if codex_enabled else 'false',
                'requested_whisper_enable': whisper_enable,
                'requested_llama_enable': llama_enable,
                'whisper_enable': 'true' if stage_ids & {'desktop.whisper', 'server.whisper'} else 'false',
                'llama_enable': 'true' if ('server.llama' in stage_ids or
                    family == 'desktop' and 'desktop.devops' in stage_ids) else 'false',
            }
            plan = {'format': 2, 'suite': suite, 'roles': roles, 'family': family,
                    'architecture': 'amd64', 'classes': selected_refs, 'profile': family + '/' + profile_id,
                    'filesystem': 'btrfs', 'mode': 'fresh',
                    'class_sources': {record['path']: hashlib.sha256(sources[record['path']]).hexdigest() for record in records},
                    'packages': packages, 'answers': answers, 'stages': stages, **profile_policy,
                    'runtime_acceptance': 'unverified', 'qualification': qualifications[family]}
            base = f'catalog/compiled/{suite}/plans/{identity}/amd64'
            outputs[base + '.json'] = encode(plan)
            outputs[base + '.tsv'] = ''.join('\t'.join(row) + '\n' for row in
                [('format', '2'), ('suite', suite), ('family', family), ('architecture', 'amd64')]
                + [('role', role) for role in roles] + [('profile', family + '/' + profile_id), ('filesystem', 'btrfs'), ('mode', 'fresh')]
                + list(profile_policy.items())
                + [('class', ref) for ref in selected_refs]
                + [('package', package) for package in packages]
                + [('answer', *answer.split(None, 3)) if len(answer.split(None, 3)) == 4
                   else ('answer', *answer.split(None, 3), '') for answer in answers]
                + [('stage', '|'.join((s['id'], s['phase'], s['selector']))) for s in stages]).encode()
            matrix.append({'suite': suite, 'role': identity, 'roles': roles, 'architecture': 'amd64',
                           'filesystem': 'btrfs', 'mode': 'fresh', 'implementation': 'candidate',
                           'runtime_acceptance': 'unverified', 'qualification': qualifications[family], 'plan': base + '.json'})
    if set(suite_classes['forky']) != set(suite_classes['trixie']):
        raise ValueError('suite physical class vocabularies differ')
    records = []
    for source_record in selection['classes']:
        record = dict(source_record)
        for field in CLASS_LIST_FIELDS:
            if field in record:
                record[field] = ' '.join(str(record[field]).replace(',', ' ').split())
        records.append(record)
    for ref, record in suite_classes['forky'].items():
        if ref.startswith('role/'):
            records.append({'Group': 'role', 'Name': ref.removeprefix('role/'),
                            'HostVariant': record['family'], 'Description': 'explicit role class ' + ref})
    for profile in selection['profiles']:
        records.append({'Group': 'profile', 'Name': profile['family'] + '/' + profile['id'],
                        'Description': 'explicit host profile ' + profile['id'],
                        'HostProfilePrefix': profile['family'], 'HostFamily': profile['filesystem'],
                        'HookFamily': profile['filesystem']})
    # Early selection validation and the frozen planner consume the same
    # physical dispatch constraints. Do not leave RequiresClasses empty while
    # only the later graph knows a toolkit requires an explicit driver class.
    for record in records:
        ref = record['Group'] + '/' + record['Name']
        if ref not in suite_classes['forky']:
            continue
        for source_field, registry_field in (('requires', 'RequiresClasses'),
                                              ('conflicts', 'RejectedClasses')):
            constraint = suite_classes['forky'][ref][source_field]
            if constraint != suite_classes['trixie'][ref][source_field]:
                raise ValueError(ref + ': suite dispatch constraints differ')
            previous = record.get(registry_field, '').split()
            if previous and previous != constraint:
                raise ValueError(ref + ': registry duplicates a different dispatch constraint')
            if constraint:
                record[registry_field] = ' '.join(constraint)
    table = ['manifest\tversion\t8', 'manifest\tclass_token_formats\tcanonical']
    state = ['[manifest]', 'version=8', 'class_token_formats=canonical', '']
    def cells(values):
        return '\t'.join(str(v) if v != '' else '__EMPTY__' for v in values)
    for group in selection['groups']:
        table.append(cells(['group', *(group.get(k, '') for k in ('Name','Required','Multi','Order','Purpose','Source','Description'))]))
        state += ['[group.' + group['Name'] + ']']
        state += [key.lower() + '=' + group[key] for key in ('Required','Multi','Order','Purpose','Source','Description') if key in group]
        state.append('')
    for record in records:
        table.append(cells(['class', record['Group'], record['Name'], *(record.get(k, '') for k in CLASS_FIELDS)]))
        state += ['[class.' + record['Group'] + '.' + record['Name'] + ']']
        state += [re.sub(r'(?<!^)(?=[A-Z])', '_', key).lower() + '=' + record[key] for key in CLASS_FIELDS if key in record]
        state.append('')
    outputs['catalog/compiled/class-registry.tsv'] = ('\n'.join(table) + '\n').encode()
    outputs['catalog/compiled/class-registry.conf'] = ('\n'.join(state) + '\n').encode()
    outputs['catalog/compiled/class-plan.tsv'] = ''.join('\t'.join(row) + '\n' for row in graph).encode()
    perl_members = []
    perl_owners = set()
    for name in sorted(sources):
        member = re.fullmatch(r'hooks/target/usr/local/lib/(common|desktop|server)/perl5/site_perl/(.+)', name)
        if member is None:
            continue
        family, relative = member.groups()
        relative = relative.removesuffix('.tmpl')
        if (family, relative) in perl_owners:
            raise ValueError('ambiguous Perl source owner')
        perl_owners.add((family, relative))
        perl_members.append((name, relative, family))
    for family, relative in perl_owners:
        if family != 'common' and ('common', relative) in perl_owners:
            raise ValueError('Perl module has overlapping common/family owners')
    outputs['catalog/compiled/shared-perl-assets.tsv'] = ''.join(
        '\t'.join(row) + '\n' for row in perl_members).encode()
    outputs['catalog/compiled/suite-qualification.tsv'] = ''.join('\t'.join(row) + '\n' for row in qualification_rows).encode()
    outputs['catalog/compiled/support-matrix.json'] = encode({'format': 1, 'tuples': matrix})
    # Capture owns membership. Fixed source addresses are interfaces at their
    # consumers; repo.env owns only configuration and genuinely shared roots.
    # These catalogs are deterministic data, never executable configuration.
    outputs['catalog/compiled/profile-assets.tsv'] = b''
    outputs['catalog/compiled/source-members.tsv'] = b''
    outputs['catalog/compiled/apt-assets.tsv'] = b''
    members = set(sources) | set(outputs) | {'catalog/compiled/release.tsv'}
    required_members, required_directory_selectors = set(), set()
    profile_asset_members: set[str] = set()
    source_call = re.compile(
        r'\b(installer_repo_file_value|bootstrap_repo_file_value|repo_file_value|'
        r'installer_stage_profile_file|desktop_stage_role_asset|'
        r'desktop_render_role_target_template(?:_deferred)?|installer_operation_context_repo)'
        r'(?:\s|\\\n)+(?:"([A-Za-z0-9_./@+${} -]+)"|'
        r"'([A-Za-z0-9_./@+${} -]+)'|([A-Za-z0-9_./@+${}-]+))")
    for name, data in sources.items():
        if not name.startswith(('scripts/', 'hooks/installer/')):
            continue
        text = data.decode()
        for match in source_call.finditer(text):
            operation = match[1]
            member = next(value for value in match.groups()[1:] if value is not None)
            if member.startswith('FILE_'):
                raise ValueError(name + ': retired per-file repository selector: ' + member)
            if '/' not in member or '$' in member and '${INSTALLER_SUITE}' not in member:
                continue  # A runtime policy value or directory selector.
            required_members.add(member)
            if operation == 'installer_stage_profile_file':
                profile_asset_members.add(member)
        required_directory_selectors.update(re.findall(
            r'(?:installer_repo_join_var|bootstrap_repo_join_var|installer_repo_asset_path)\s+["\']?(DIR_[A-Z0-9_]+)', text))
    apt_source_roots = {}
    for suite, classes in suite_classes.items():
        schema = re.search(r"source_repo_supported='([^']+)'", sources['scripts/common/source.sh'].decode())
        if schema is None:
            raise ValueError('repository data loader has no supported vocabulary')
        selectors = repository_data(sources['repo.env'].decode(), suite, set(schema[1].split()))
        apt_roots = {family: selectors[key] for family, key in (
            ('common', 'DIR_TARGET_APT'), ('desktop', 'DIR_TARGET_APT_DESKTOP'),
            ('server', 'DIR_TARGET_APT_SERVER'))}
        for family in ('desktop', 'server'):
            other = 'server' if family == 'desktop' else 'desktop'
            if (apt_roots['common'] == apt_roots[family]
                    or apt_roots['common'].startswith(apt_roots[family] + '/')
                    or apt_roots[family] == apt_roots[other]
                    or apt_roots[family].startswith(apt_roots[other] + '/')):
                raise ValueError('overlapping APT common/role source owners: ' + suite)
        apt_source_roots[suite] = apt_roots
        missing = required_directory_selectors - set(selectors)
        if missing:
            raise ValueError('installer caller lacks a shared source root: ' + ', '.join(sorted(missing)))
        missing_members = {member.replace('${INSTALLER_SUITE}', suite) for member in required_members} - members
        if missing_members:
            raise ValueError('fixed source call names no captured member: ' + ', '.join(sorted(missing_members)))
        for record in classes.values():
            for stage in record['stages']:
                if stage['selector'] not in members:
                    raise ValueError(stage['id'] + ': missing phase provider source')
    outputs['catalog/compiled/profile-assets.tsv'] = ''.join(
        member + '\tprofile\n' for member in sorted(profile_asset_members)).encode()
    inventory, apt = [], []
    for member in sorted(members):
        safe_path(member)
        suite_match = re.match(r'frontends/(forky|trixie)/', member)
        suite = suite_match[1] if suite_match else 'any'
        family_match = re.match(
            r'hooks/target/(?:etc/(?:systemd|apparmor(?:\.d)?|tmpfiles\.d|sysctl\.d)|'
            r'usr/local/(?:bin|sbin|libexec|lib|share))/(common|desktop|server)/', member)
        family = family_match[1] if family_match else 'any'
        inventory.append((member, family, suite))
        for selected_suite, apt_roots in sorted(apt_source_roots.items()):
            matches = [(family, root) for family, root in apt_roots.items()
                       if member.startswith(root + '/')]
            if not matches:
                continue
            # Role roots may be nested under the common root. The most
            # specific configured owner wins; disjoint role roots also work.
            selected_family, apt_root = max(matches, key=lambda item: len(item[1]))
            leaf = member[len(apt_root) + 1:]
            kind, separator, remainder = leaf.partition('/')
            if not separator:
                kind, remainder = 'root', leaf
            apt.append((selected_suite, selected_family, kind, remainder, member))
    outputs['catalog/compiled/source-members.tsv'] = (
        'format\t1\n' + ''.join('\t'.join(row) + '\n' for row in inventory)).encode()
    outputs['catalog/compiled/apt-assets.tsv'] = (
        'format\t1\n' + ''.join('\t'.join(row) + '\n' for row in sorted(apt))).encode()
    return outputs, {}, {'format': 1, 'tuples': matrix}
